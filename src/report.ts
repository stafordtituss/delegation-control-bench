import type { BenchmarkResults } from './bench';
import { CONTROL_PLACEMENT } from './pep';

const row = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`;

export function renderMarkdown(r: BenchmarkResults): string {
  const out: string[] = [];
  out.push('# Results', '');
  out.push('Generated by `npm run bench`. Do not edit by hand.', '');
  out.push(`Cedar ${r.tools.cedar}; AMEP JavaScript verifier ${r.tools.amep}; ${r.scenarioCount} delegation-suite scenarios.`, '');

  out.push('## 1. Enforcement: final-token PEP vs full-chain PEP (same Cedar policy)', '');
  out.push(row(['Configuration', 'Pass', 'False allow', 'False deny']));
  out.push(row(['---', '---', '---', '---']));
  for (const s of r.enforcement.summaries) {
    out.push(row([s.config, `${s.pass}/${s.total}`, s.falseAllow.join(', ') || '—', s.falseDeny.join(', ') || '—']));
  }
  out.push('');
  out.push(row(['Scenario', 'Expected', 'final-token', 'full-chain', 'Deciding policies (full-chain)']));
  out.push(row(['---', '---', '---', '---', '---']));
  for (const e of r.enforcement.rows) {
    const ft = e.decisions['final-token'];
    const fc = e.decisions['full-chain'];
    const mark = (d: typeof ft) => `${d.decision}${d.outcome === 'fail' ? ' ✗' : ''}`;
    out.push(row([`${e.scenarioId} ${e.title}`, e.expected, mark(ft), mark(fc), fc.policies.join(', ') || '(default deny)']));
  }
  out.push('');
  out.push('### Where each control lives in the full-chain configuration', '');
  out.push(row(['Control', 'In the Cedar policy', 'Computed by the PEP']));
  out.push(row(['---', '---', '---']));
  for (const c of CONTROL_PLACEMENT) out.push(row([c.control, c.cedar, c.pep]));
  out.push('');

  out.push('## 2. Evidence: reference verifier vs AMEP verifier', '');
  out.push(row(['Evidence variant', 'Cases', 'Agree', 'Reference (P / V / U)', 'AMEP (P / V / U)']));
  out.push(row(['---', '---', '---', '---', '---']));
  for (const [variant, v] of Object.entries(r.evidence.byVariant)) {
    const fmt = (x: { preserved: number; violated: number; unresolved: number }) => `${x.preserved} / ${x.violated} / ${x.unresolved}`;
    out.push(row([variant, v.cases, v.agree, fmt(v.maestro), fmt(v.amep)]));
  }
  out.push('', 'P = preserved, V = violated, U = unresolved.', '');
  const sv = r.evidence.sensitivity;
  out.push('### Sensitivity: a signed deny with no observation of the effect', '');
  out.push(`${sv.question} Across ${sv.cases} denied scenarios with decision-log-only evidence:`, '');
  out.push(row(['Verifier', 'Preserved']));
  out.push(row(['---', '---']));
  out.push(row(['Reference verifier', `${sv.referencePreserved}/${sv.cases}`]));
  out.push(row(['AMEP, enforcement point fail mode unknown', `${sv.amepPreservedWhenFailModeUnknown}/${sv.cases}`]));
  out.push(row(['AMEP, enforcement point declared fail-closed (spec 10.3)', `${sv.amepPreservedWhenFailClosed}/${sv.cases}`]));
  out.push('');
  out.push('### Disagreements', '');
  const diffs = r.evidence.rows.filter((x) => !x.agree);
  if (diffs.length === 0) out.push('None.');
  else {
    out.push(row(['Scenario', 'Variant', 'Reference', 'AMEP (invariant)', 'Why']));
    out.push(row(['---', '---', '---', '---', '---']));
    for (const d of diffs) out.push(row([d.scenarioId, d.variant, d.maestro, `${d.amep.outcome} (${d.amep.invariant})`, d.difference ?? '']));
  }
  out.push('');
  return out.join('\n');
}
